"""Write corpus.md and audit.md from the data files, so that every count and table cell comes from the data.

Usage: python3 render.py
"""

from __future__ import annotations

import collections
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
GROUPS = {
    "several-actors": "Several acting agents",
    "actor-and-llm-checker": "One acting agent and a model that checks it",
    "single-actor": "One acting agent and a programmatic check",
    "out": "Left out",
}
COLUMNS = ("origin", "setting", "gap", "models", "training", "runs", "release", "read", "note")


def cell(value: object) -> str:
    text = ", ".join(value) if isinstance(value, list) else str(value or "")
    return text.replace("|", "\\|")


def link(record: dict) -> str:
    if record["id"].startswith("arXiv:"):
        return f"[{record['id']}](https://arxiv.org/abs/{record['id'][6:]})"
    return record["id"]


def main() -> None:
    data = json.loads((HERE / "corpus.json").read_text(encoding="utf-8"))
    records = data["records"]
    counts = collections.Counter(record["group"] for record in records)
    kept = len(records) - counts["out"]
    lines = ["# Reward hacking in systems of LLM agents: the studies found so far", "",
             f"Generated by `render.py` from `corpus.json`, collected {data['collected']}. The `read` field says",
             "how much of each source was read; a field that says \"not stated in the text read\" is not a finding",
             "about the paper.", "",
             "| Group | Records |", "|---|---|"]
    lines += [f"| {GROUPS[group]} | {counts[group]} |" for group in GROUPS]
    released = [r for r in records if r["group"] != "out" and r["release"].startswith("http")]
    lines += ["", f"Of the {kept} records kept, {len(released)} give an address for code or data in the text read.",
              ""]
    for group in GROUPS:
        lines += [f"## {GROUPS[group]}", ""]
        if group == "out":
            lines += ["| Source | Title | Authors | Reason |", "|---|---|---|---|"]
            lines += [f"| {link(r)} | {cell(r['title'])} | {cell(r['authors'])} | {cell(r['reason'])} |"
                      for r in records if r["group"] == group]
        else:
            for record in (r for r in records if r["group"] == group):
                lines += [f"### {record['title']}", "",
                          f"{link(record)}, {record['authors']}, {record['date']}"
                          + (f". Why it counts: {cell(record['basis'])}." if record["basis"] else "."), ""]
                lines += [f"- **{name}:** {cell(record[name])}" for name in COLUMNS if record.get(name)]
                lines.append("")
        lines.append("")
    lines += ["## Not read yet", ""] + [f"- {item}" for item in data["not_read"]] + [""]
    (HERE / "corpus.md").write_text("\n".join(lines), encoding="utf-8")
    print({GROUPS[group]: counts[group] for group in GROUPS}, "| with an address for code or data:", len(released))
    audit(records)


def audit(records: list[dict]) -> None:
    """The item-by-paper table of audit.json, with what each paper and each item leaves open."""
    spec = json.loads((HERE / "items.json").read_text(encoding="utf-8"))
    papers = json.loads((HERE / "audit.json").read_text(encoding="utf-8"))["papers"]
    by_id = {record["id"]: record for record in records}
    label = {key: by_id[key]["authors"].replace(" et al.", "").split(",")[0].split(" and ")[0].split()[-1]
             for key in papers}
    lines = ["# What seven reports on reward hacking let a reader determine", "",
             f"Generated by `render.py` from `audit.json` and `items.json` (version {spec['version']} of the items).",
             spec["question"], "",
             "Scale: " + "; ".join(f"{key} = {text}" for key, text in spec["scale"].items()) + ".",
             "One reader scored each paper once, and the `read` line of a paper says which parts were read.", "",
             "## By paper", "", "| Paper | Applicable | Determined | Partly | Open |", "|---|---|---|---|---|"]
    totals = collections.Counter()
    for key, paper in papers.items():
        got = [entry["score"] for entry in paper["scores"].values() if entry["score"] != "NA"]
        totals.update(got)
        lines.append(f"| {label[key]}, {link(by_id[key])} | {len(got)} | {got.count(2)} | {got.count(1)} "
                     f"| {got.count(0)} |")
    all_scores = sum(totals.values())
    lines += [f"| All | {all_scores} | {totals[2]} | {totals[1]} | {totals[0]} |", "",
              "## By item", "", "| Item | " + " | ".join(label[key] for key in papers) + " | Open or partly |",
              "|---|" + "---|" * (len(papers) + 1)]
    group = None
    for item in spec["items"]:
        if item["id"][0] != group:
            group = item["id"][0]
            lines.append(f"| **{spec['groups'][group]}** |" + " |" * (len(papers) + 1))
        scores = [papers[key]["scores"][item["id"]]["score"] for key in papers]
        applicable = [score for score in scores if score != "NA"]
        short = sum(score < 2 for score in applicable)
        lines.append(f"| {item['id']} {cell(item['text'])} | " + " | ".join(str(score) for score in scores)
                     + f" | {short} of {len(applicable)} |")
    lines += ["", "## Evidence", ""]
    for key, paper in papers.items():
        lines += [f"### {label[key]}: {by_id[key]['title']}", "",
                  f"{link(by_id[key])}. Read: {paper['read']}.", ""]
        lines += [f"- **{item}** ({entry['score']}): {cell(entry['evidence'])}"
                  for item, entry in paper["scores"].items()]
        lines.append("")
    (HERE / "audit.md").write_text("\n".join(lines), encoding="utf-8")
    print("audit:", len(papers), "papers,", all_scores, "applicable scores:", dict(sorted(totals.items())))


if __name__ == "__main__":
    main()
